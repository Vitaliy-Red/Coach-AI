function fmt(sec) {
  const s = Math.max(0, Math.round(Number(sec) || 0));
  return `${String(Math.floor(s / 60)).padStart(2, '0')}:${String(s % 60).padStart(2, '0')}`;
}

export function scenarioExists(id) {
  return Boolean(findScenario(id) && PRIVATE[id]);
}

