function genderLine(g) {
  return g === 'male'
    ? 'Ты мужчина: говори о себе в мужском роде.'
    : 'Ты женщина: говори о себе в женском роде.';
}

function bullet(list) {
  return list.map((x) => `- ${x}`).join('\n');
}

// Сценарий с администратором выбирается отдельно от случайного рекрутера.
const RANDOM_WEIGHTS = {
  hh: 33, silence: 22, 'smart-dump': 13, 'workers-avito': 9, price: 23, approve: 14, season: 23, 'young-only': 5,
  'send-kp': 30, charges: 12, access: 18, renewal: 15, 'resume-limit': 10, multicity: 10,
};

export function resolveScenario(id, level, rnd = Math.random) {
  if (id !== 'random') return { id, level, hidden: false };
  const entries = Object.entries(RANDOM_WEIGHTS);
  const total = entries.reduce((s, [, w]) => s + w, 0);
  let r = rnd() * total;
  let pick = entries[0][0];
  for (const [k, w] of entries) { if ((r -= w) <= 0) { pick = k; break; } }
  const lv = level && level !== 'auto' ? level : (() => { const x = rnd(); return x < 0.25 ? 'easy' : x < 0.75 ? 'medium' : 'hard'; })();
  return { id: pick, level: lv, hidden: true };
}

export function resolveGender(priv, rnd = Math.random) {
  if (!priv || priv.gender === 'random') return rnd() < 0.7 ? 'female' : 'male';
  return priv.gender;
}

export function buildClientPrompt({ id, level, mode, gender }) {
  const pub = findScenario(id);
  const priv = PRIVATE[id];
  if (!pub || !priv) throw new Error('unknown scenario ' + id);
  const lv = LEVEL_RULES[level] ? level : 'medium';
  const routing = pub.type === 'routing';
  const parts = [routing
    ? 'Ты администратор действующего клиента. Говори коротко и по-русски. Оставайся в роли администратора весь звонок.'
    : BASE_ROLE];

  parts.push(`# ЛЕГЕНДА ЭТОГО ЗВОНКА (держи весь разговор, новых фактов не придумывай)
${priv.legend}
${genderLine(gender)}
Как снимаешь трубку: «${priv.pickup || 'Алло?'}»
Что менеджер знает о тебе до звонка: ${pub.context}`);

  const objections = priv.objections.slice(0, LEVEL_OBJECTIONS[lv]);
  parts.push(`# ТВОИ ВОЗРАЖЕНИЯ (в этом порядке важности)
${bullet(objections)}`);

  parts.push(`# ПРИМЕРЫ РЕПЛИК
Используй эти фразы по смыслу и только на допустимом этапе разговора. Новых возражений, цифр и фактов не выдумывай. На вопрос о неизвестном ответь коротко: «надо посмотреть».
${bullet(priv.phrases)}`);

  if (!routing) parts.push(BASE_SPEECH);
  parts.push(routing ? ROUTING_FLOW : `${SALES_FLOW}
Для перехода к презентации менеджер должен выяснить: ${DISCOVERY[id]}.`);
  parts.push(`Что тебя смягчает именно в этом звонке:
${bullet(priv.softeners)}
Что тебя раздражает именно в этом звонке:
${bullet(priv.irritants)}`);
  if (!routing) parts.push(BASE_OUTCOME, `# СЛОЖНОСТЬ\n${LEVEL_RULES[lv]}`);
  if (priv.outcomeNote) parts.push(`Особенность этого звонка: ${priv.outcomeNote}`);
  parts.push(mode === 'voice' ? VOICE_FORMAT : TEXT_FORMAT);
  return parts.join('\n\n');
}

